import { notFound } from "next/navigation";
import { prisma } from "@/lib/prisma";
import { auth } from "@/lib/auth";
import { hasMarketAccess, hasStaffArea } from "@/lib/rbac";
import { itemQrSvg, itemScanUrl } from "@/lib/item-qr";
import type { ItemKind } from "@/lib/item-number";
import { BackLink } from "@/components/admin/BackLink";
import { PrintButton } from "@/components/admin/PrintButton";

const MAX_LABELS = 200;

/**
 * A printable sheet of QR labels for the items picked in the catalog list's
 * bulk toolbar (?ids=a,b,c) — each label is the QR code, the item number and
 * the name. Shared by /admin/gems/qr-labels and /admin/jewelry/qr-labels.
 */
export async function QrLabelSheet({ kind, ids }: { kind: ItemKind; ids: string[] }) {
  const user = (await auth())?.user;
  if (!user || !hasStaffArea(user, "catalog")) notFound();

  const wanted = ids.slice(0, MAX_LABELS);
  const select = { id: true, itemNumber: true, name: true, market: true } as const;
  const rows =
    kind === "gemstone"
      ? await prisma.gemstone.findMany({ where: { id: { in: wanted } }, select, orderBy: { itemNumber: "asc" } })
      : await prisma.jewelryPiece.findMany({ where: { id: { in: wanted } }, select, orderBy: { itemNumber: "asc" } });
  // Only items in a store this person may see — never assumed from the list
  // they were looking at.
  const items = rows.filter((row) => hasMarketAccess(user, row.market));
  const labels = await Promise.all(items.map(async (item) => ({ ...item, svg: await itemQrSvg(item.itemNumber) })));
  const listPath = kind === "gemstone" ? "/admin/gems" : "/admin/jewelry";

  return (
    <div>
      <div className="print:hidden">
        <BackLink href={listPath} label={kind === "gemstone" ? "Back to Gemstones" : "Back to Jewelry"} />
        <div className="flex flex-wrap items-center justify-between gap-3">
          <h1 className="font-serif text-3xl text-charcoal">QR Labels</h1>
          {labels.length > 0 && <PrintButton />}
        </div>
        <p className="mt-1 text-sm text-charcoal/60">
          {labels.length} label{labels.length === 1 ? "" : "s"}. Each code opens the item&apos;s product page by its item
          number, so labels keep working if an item is renamed.
          {ids.length > MAX_LABELS && ` Only the first ${MAX_LABELS} selected items are shown.`}
        </p>
      </div>

      {labels.length === 0 ? (
        <p className="mt-8 text-sm text-charcoal/65">No items selected. Tick items in the list, then choose &ldquo;Print QR labels&rdquo;.</p>
      ) : (
        <div className="mt-6 grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-4 print:mt-0 print:grid-cols-4 print:gap-2">
          {labels.map((label) => (
            <figure
              key={label.id}
              className="flex break-inside-avoid flex-col items-center rounded-lg border border-border-subtle bg-white p-3 text-center text-black print:rounded-none print:border-black/30"
            >
              <div
                className="w-full max-w-[9rem] [&>svg]:h-auto [&>svg]:w-full"
                role="img"
                aria-label={`QR code linking to ${itemScanUrl(label.itemNumber)}`}
                // Generated by the qrcode library from our own URL — no user input.
                dangerouslySetInnerHTML={{ __html: label.svg }}
              />
              <figcaption className="mt-1 w-full">
                <span className="block font-mono text-sm font-bold tracking-wider">{label.itemNumber}</span>
                <span className="block truncate text-xs text-black/70">{label.name}</span>
              </figcaption>
            </figure>
          ))}
        </div>
      )}
    </div>
  );
}

export function parseIdsParam(value: string | string[] | undefined): string[] {
  const raw = Array.isArray(value) ? value.join(",") : (value ?? "");
  return [...new Set(raw.split(",").map((id) => id.trim()).filter(Boolean))];
}
